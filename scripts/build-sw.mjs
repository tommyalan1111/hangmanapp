import { createHash } from "node:crypto";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";

const root = process.cwd();
const dist = path.join(root, "dist");

async function walk(directory, base = "") {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = [];
  for (const entry of entries) {
    const relative = base ? `${base}/${entry.name}` : entry.name;
    if (entry.isDirectory()) {
      files.push(...(await walk(path.join(directory, entry.name), relative)));
    } else if (entry.isFile()) {
      files.push(relative);
    }
  }
  return files;
}

const allFiles = (await walk(dist)).filter((file) => file !== "sw.js").sort();
const fingerprintParts = [];
for (const file of allFiles) {
  const details = await stat(path.join(dist, file));
  fingerprintParts.push(`${file}:${details.size}`);
}
const fingerprint = createHash("sha256").update(fingerprintParts.join("|")).digest("hex").slice(0, 10);
const assets = ["./", ...allFiles.map((file) => `./${file}`)];
const version = `reel-hangman-${fingerprint}`;

const serviceWorker = `/* Generated by scripts/build-sw.mjs. */
const CACHE = "${version}";
const ASSETS = ${JSON.stringify(assets, null, 2)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches
      .open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET") return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === "navigate") {
    event.respondWith(
      fetch(request).catch(() => caches.match("./index.html").then((cached) => cached || caches.match("./"))),
    );
    return;
  }

  event.respondWith(
    caches.match(request).then((cached) => {
      if (cached) return cached;
      return fetch(request).then((response) => {
        if (!response || response.status !== 200 || response.type === "opaque") return response;
        const copy = response.clone();
        caches.open(CACHE).then((cache) => cache.put(request, copy));
        return response;
      });
    }),
  );
});
`;

await writeFile(path.join(dist, "sw.js"), serviceWorker, "utf8");
await writeFile(path.join(dist, "version.json"), JSON.stringify({ version, assets: allFiles.length }, null, 2), "utf8");

const swSize = (await stat(path.join(dist, "sw.js"))).size;
console.log(`Service worker generated: ${allFiles.length} assets, ${version}, ${swSize} bytes`);
